def hotwords(text):
    found = []
    i = 0
    while i < len(text):
        for w in HOTWORDS:
            if text.startswith(w, i):
                if w not in found:
                    found.append(w)
                i += len(w)
                break
        else:
            i += 1
    return "；".join(found)


