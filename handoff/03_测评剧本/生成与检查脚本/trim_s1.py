import json, sys
p = sys.argv[1]
d = json.load(open(p, encoding="utf-8"))
repl = {
    "今晚八点有一场演出，叫《云上花间》，来丽江的客人大多都会去看，票价每人二百八十元。":
        "今晚八点有一场演出，叫《云上花间》，来丽江的客人大多会去看，票价每人二百八十元。",
    "A区是第一排到第十排，B区是第十一排到第二十五排，B区看得也挺清楚。":
        "A区是第一排到第十排，B区是第十一排到第二十五排，也看得清楚。",
    "陈导，我再确认一下，合同上写的第三天，就是今天十月十五号，对吧？":
        "陈导，再确认一下，合同上的第三天就是今天十月十五号吧？",
    "对，其他二十三位都看B区，不用交钱。八零六房间那位大姐也转了两百八，待会儿全退给她。":
        "对，其他二十三位看B区，不用交钱。八零六房间的大姐也转了两百八，待会儿退给她。",
    "七十分钟左右，九点十分结束，九点四十以前能回到酒店。":
        "七十分钟左右，九点十分结束，九点四十以前回到酒店。",
    "好，一二一八房间，五百四，我记上了，现在就转。":
        "好，一二一八房间，五百四，现在就转。",
    "你们这个团看B区不用另外收钱，想换A区的，补一百块差价就行。":
        "你们团看B区不用另外收钱，想换A区，补一百块差价就行。",
}
hit = set()
for ln in d["scripts"][0]["lines"]:
    if ln["text"] in repl:
        hit.add(ln["text"])
        ln["text"] = repl[ln["text"]]
missing = set(repl) - hit
assert not missing, missing
json.dump(d, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
print("replaced", len(hit))
